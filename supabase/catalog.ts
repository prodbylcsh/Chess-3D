// Copies the shop catalogue (supabase/functions/_shared/shop.ts) into the database's
// `items` table, so purchases and ownership (`player_items`) always point at real items:
//
//   node supabase/catalog.ts --linked     the live project (deploy workflow, after `db push`)
//   node supabase/catalog.ts --local      the local stack (.claude/skills/local-supabase)
//   node supabase/catalog.ts              print the SQL only
//
// New items are added, changed ones updated, and items taken out of the shop
// (RETIRED_ITEMS, or simply gone from ITEMS) are kept but marked retired: players who
// own them keep them. Season reward icons are added by the database when handed out.
import { spawnSync } from 'node:child_process';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ITEMS, RETIRED_ITEMS } from './functions/_shared/shop.ts';

const quote = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function catalogSql(): string {
  const rows = [
    ...ITEMS.map((i) => `(${quote(i.id)}, ${quote(i.category)}, ${quote(i.rarity)}, ${i.price}, ${i.forSale}, false)`),
    ...RETIRED_ITEMS.map((i) => `(${quote(i.id)}, ${quote(i.category)}, 'common', 0, false, true)`),
  ];
  const known = [...ITEMS, ...RETIRED_ITEMS].map((i) => quote(i.id)).join(', ');
  // one statement (the CLI runs a single one): upsert the catalogue, then retire whatever
  // else is no longer in it (season icons are never in the catalogue and stay as they are)
  return `-- generated by supabase/catalog.ts
with catalogue as (
  insert into public.items as i (id, category, rarity, price, for_sale, retired) values
    ${rows.join(',\n    ')}
  on conflict (id) do update set
    category = excluded.category,
    rarity = case when excluded.retired then i.rarity else excluded.rarity end,
    price = case when excluded.retired then i.price else excluded.price end,
    for_sale = excluded.for_sale,
    retired = excluded.retired,
    updated_at = now()
  where (i.category, i.rarity, i.price, i.for_sale, i.retired) is distinct from
    (excluded.category, case when excluded.retired then i.rarity else excluded.rarity end,
     case when excluded.retired then i.price else excluded.price end, excluded.for_sale, excluded.retired)
  returning 1
)
update public.items set retired = true, for_sale = false, updated_at = now()
where not retired and id not like 'season-%' and id not like 'premium-%' and id not in (${known});
`;
}


const target = process.argv[2];
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const sql = catalogSql();
  if (!target) {
    console.log(sql);
  } else if (target === '--linked' || target === '--local') {
    const file = join(mkdtempSync(join(tmpdir(), 'catalog-')), 'catalog.sql');
    writeFileSync(file, sql);
    const run = spawnSync('npx', ['supabase', 'db', 'query', target, '-f', file], { stdio: ['ignore', 'pipe', 'inherit'], encoding: 'utf8' });
    if (run.status !== 0) process.exit(run.status ?? 1);
    console.log(`catalogue synced (${ITEMS.length} items, ${RETIRED_ITEMS.length} retired)`);
  } else {
    console.error('usage: node supabase/catalog.ts [--linked | --local]');
    process.exit(1);
  }
}
